export function getStoredLanguage(): SupportedLanguageCode {
  if (typeof window === 'undefined') return 'en';
  try {
    const raw = localStorage.getItem('user');
    if (raw) {
      const user = JSON.parse(raw);
      if (user?.language && user.language in TRANSLATIONS) {
        return user.language as SupportedLanguageCode;
      }
    }
  } catch {
    // fallback
  }
  return 'en';
}

/**
 * Hook providing reactive translation function that immediately updates
 * whenever the user changes their interface language in settings.
 */
export function useTranslation() {
  const [lang, setLang] = useState<SupportedLanguageCode>(getStoredLanguage);

  useEffect(() => {
    const updateLang = () => {
      setLang(getStoredLanguage());
    };
    window.addEventListener('finlytix-preferences-updated', updateLang);
    window.addEventListener('storage', updateLang);
    return () => {
      window.removeEventListener('finlytix-preferences-updated', updateLang);
      window.removeEventListener('storage', updateLang);
    };
  }, []);

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    if (key in langDict) {
      return langDict[key];
    }
    // Fallback to English dictionary
    if (key in TRANSLATIONS.en) {
      return TRANSLATIONS.en[key];
    }
    return fallback || key;
  };

  return {
    t,
    currentLanguage: lang,
    supportedLanguages: SUPPORTED_LANGUAGES,
  };
}
